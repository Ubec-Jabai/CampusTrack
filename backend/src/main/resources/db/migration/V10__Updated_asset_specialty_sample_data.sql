-- V7 derives asset specialty from category, so every OTHER asset became GENERAL.
-- These sample assets need the trade that actually services them.

UPDATE assets
SET specialty = CASE id
    WHEN 1002 THEN 'ELECTRICAL'
    WHEN 1003 THEN 'PLUMBING'
    WHEN 1004 THEN 'STRUCTURAL'
    WHEN 1011 THEN 'PLUMBING'
    WHEN 1012 THEN 'HVAC'
    WHEN 1018 THEN 'PLUMBING'
    WHEN 1019 THEN 'STRUCTURAL'
    WHEN 1026 THEN 'EQUIPMENT'
    WHEN 1029 THEN 'PLUMBING'
    WHEN 1030 THEN 'STRUCTURAL'
    WHEN 1037 THEN 'PLUMBING'
    WHEN 1041 THEN 'STRUCTURAL'
    WHEN 1045 THEN 'PLUMBING'
END
WHERE id IN (1002, 1003, 1004, 1011, 1012, 1018, 1019, 1026, 1029, 1030, 1037, 1041, 1045);
