ALTER TABLE assets
    ADD COLUMN specialty VARCHAR(50) NULL AFTER category;

UPDATE assets
SET specialty = CASE category
    WHEN 'COMPUTER' THEN 'NETWORK_IT'
    WHEN 'NETWORK_EQUIPMENT' THEN 'NETWORK_IT'
    WHEN 'PROJECTOR' THEN 'EQUIPMENT'
    WHEN 'LAB_EQUIPMENT' THEN 'EQUIPMENT'
    WHEN 'OFFICE_EQUIPMENT' THEN 'EQUIPMENT'
    WHEN 'AIRCONDITIONER' THEN 'HVAC'
    WHEN 'FURNITURE' THEN 'FURNITURE'
    WHEN 'ELECTRICAL_EQUIPMENT' THEN 'ELECTRICAL'
    ELSE 'GENERAL'
END
WHERE specialty IS NULL;

UPDATE user_profiles p
JOIN users u ON u.id = p.user_id
SET p.available = TRUE
WHERE u.user_role = 'WORKER'
  AND p.available IS NULL;

ALTER TABLE assets
    MODIFY COLUMN specialty VARCHAR(50) NOT NULL DEFAULT 'GENERAL';
